// Now build the updated SOUNDTRACKS object
const updatedSoundtracks = {};

for (const [id, track] of Object.entries(SOUNDTRACKS)) {
  const ext = EXTENSIONS[id];
  if (ext) {
    updatedSoundtracks[id] = {
      ...track,
      lead: [...track.lead, ...(ext.addLead || [])],
      bass: [...track.bass, ...(ext.addBass || [])]
    };
  } else {
    // If no explicit extension, loop the existing lead & bass twice to double duration
    updatedSoundtracks[id] = {
      ...track,
      lead: [...track.lead, ...track.lead],
      bass: [...track.bass, ...track.bass]
    };
  }
}

// Generate the updated AudioSynth.js content
const serializedSoundtracks = 'export const SOUNDTRACKS = ' + JSON.stringify(updatedSoundtracks, null, 2) + ';\n\n';

const startMarker = 'export const SOUNDTRACKS = {';
const endMarker = 'function expandPattern(pattern) {';

const startIndex = code.indexOf(startMarker);
const endIndex = code.indexOf(endMarker);

if (startIndex === -1 || endIndex === -1) {
  console.error('Could not find SOUNDTRACKS markers in AudioSynth.js');
  process.exit(1);
}

const newCode = code.slice(0, startIndex) + serializedSoundtracks + code.slice(endIndex);
fs.writeFileSync(AUDIO_SYNTH_PATH, newCode, 'utf8');

console.log('Successfully updated all soundtracks in AudioSynth.js!');
